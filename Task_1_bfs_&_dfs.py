from collections import deque
graph = {
    'A':['B','C'],
    'B':[],
    'C':[]
}
visited=set()
queue=deque()
start='A'
queue.append(start)
print("BFS Travesal:")
while queue:
  node = queue.popleft()
  if node not in visited:
    print(node, end=" ")
    visited.add(node)
    for neighbour in graph[node]:
      queue.append(neighbour)


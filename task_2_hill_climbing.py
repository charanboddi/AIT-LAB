distance = [
    [0, 10, 15, 20],
    [10, 0, 35, 25],
    [15, 35, 0, 30],
    [20, 25, 30, 0]
]


def route_length(route):
    total = 0

    for i in range(len(route) - 1):
        total += distance[route[i]][route[i + 1]]

    # Return to starting city
    total += distance[route[-1]][route[0]]

    return total


def generate_neighbours(route):
    neighbours = []
    n = len(route)

    for i in range(n):
        for j in range(i + 1, n):

            new_route = route[:]

            # Swap two cities
            new_route[i], new_route[j] = new_route[j], new_route[i]

            neighbours.append(new_route)

    return neighbours


def hill_climbing():

    # Fixed initial route
    current = [0, 1, 3, 1]

    current_cost = route_length(current)

    while True:

        neighbours = generate_neighbours(current)

        best = current
        best_cost = current_cost

        for neighbour in neighbours:

            cost = route_length(neighbour)

            if cost < best_cost:
                best = neighbour
                best_cost = cost

        # Stop when there is no better neighbour
        if best_cost == current_cost:
            break

        current = best
        current_cost = best_cost

    return current, current_cost


route, cost = hill_climbing()

print("Best Route:", route)
print("Minimum Distance:", cost)
import heapq

I, G = ((1, 2, 3), (8, 0, 4), (7, 6, 5)), ((2, 8, 1), (0, 4, 3), (7, 6, 5))
pos = {v: (r, c) for r, row in enumerate(G) for c, v in enumerate(row) if v}
h = lambda s: sum(abs(r - pos[v][0]) + abs(c - pos[v][1]) for r, row in enumerate(s) for c, v in enumerate(row) if v)

q, vis, path = [(h(I), 0, I, [I])], {I}, []
while q:
    f, g, cur, p = heapq.heappop(q)
    if cur == G: path = p; break
    r, c = next((r, c) for r, row in enumerate(cur) for c, v in enumerate(row) if v == 0)
    for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
        nr, nc = r + dr, c + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            lst = [list(row) for row in cur]
            lst[r][c], lst[nr][nc] = lst[nr][nc], lst[r][c]
            nxt = tuple(tuple(row) for row in lst)
            if nxt not in vis:
                vis.add(nxt)
                heapq.heappush(q, (g + 1 + h(nxt), g + 1, nxt, p + [nxt]))

for i, s in enumerate(path):
    print(f"Step {i}:\n" + "\n".join(" ".join(str(x) if x else " " for x in r) for r in s) + "\n" + "-"*5)
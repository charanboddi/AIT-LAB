class Node:
    def __init__(self, name, value=None, children=None):
        self.name, self.value, self.children = name, value, children or []
    @property
    def is_terminal(self):
        return not self.children
def minimax(node, depth, is_max):
    if depth == 0 or node.is_terminal:
        return node.value

    scores = [minimax(child, depth - 1, not is_max) for child in node.children]
    return max(scores) if is_max else min(scores)
A, B, C, D, E, F, G, H = [Node(n, v) for n, v in zip("ABCDEFGH", [3, 5, 2, 9, 12, 5, 23, 23])]
root = Node("Root", children=[
    Node("Branch_Left", children=[
        Node("Child_1", children=[A, B]),
        Node("Child_2", children=[C, D])
    ]),
    Node("Branch_Right", children=[
        Node("Child_3", children=[E, F]),
        Node("Child_4", children=[G, H])
    ])
])
print(f"The optimal value at the Root node is: {minimax(root, depth=3, is_max=True)}")